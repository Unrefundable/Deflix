#!/usr/bin/env python3
"""Check the Deflix skin XML before a release.

Checks:
  1. Every skin XML file is well-formed.
  2. Every <include file="..."/> in 1080i points at an existing file.
  3. Every include reference resolves to an <include name="..."> definition.

References built from $PARAM[...] or generated by Skin Shortcuts at runtime
(skinshortcuts-*) cannot be resolved statically and are skipped.

Usage:
  python3 tools/check_skin.py
"""

from __future__ import annotations

import sys
from pathlib import Path
from xml.etree import ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SKIN_DIR = ROOT / "1080i"
XML_GLOBS = ("1080i/*.xml", "extras/**/*.xml", "shortcuts/*.xml", "colors/*.xml", "addon.xml")
GENERATED_PREFIXES = ("skinshortcuts-",)
# Written on the device by Skin Shortcuts' buildxml; never in the repo.
GENERATED_FILES = {"script-skinshortcuts-includes.xml"}


def skin_xml_files() -> list[Path]:
    files: set[Path] = set()
    for pattern in XML_GLOBS:
        files.update(p for p in ROOT.glob(pattern) if not p.name.startswith("._"))
    return sorted(files)


def is_static_name(name: str) -> bool:
    return "$" not in name and not name.startswith(GENERATED_PREFIXES)


def main() -> int:
    errors: list[str] = []
    trees: dict[Path, ET.ElementTree] = {}

    for path in skin_xml_files():
        try:
            trees[path] = ET.parse(path)
        except ET.ParseError as exc:
            errors.append(f"{path.relative_to(ROOT)}: invalid XML: {exc}")

    defined: set[str] = set()
    references: dict[str, set[str]] = {}
    for path, tree in trees.items():
        if path.parent != SKIN_DIR:
            continue
        rel = str(path.relative_to(ROOT))
        for elem in tree.iter("include"):
            if elem.get("name"):
                defined.add(elem.get("name"))
            if elem.get("file"):
                if elem.get("file") not in GENERATED_FILES and not (SKIN_DIR / elem.get("file")).is_file():
                    errors.append(f"{rel}: include file not found: {elem.get('file')}")
                continue
            ref = elem.get("content") or ((elem.text or "").strip() if len(elem) == 0 else "")
            if ref and is_static_name(ref):
                references.setdefault(ref, set()).add(rel)

    for name in sorted(set(references) - defined):
        where = ", ".join(sorted(references[name]))
        errors.append(f"unresolved include '{name}' used in {where}")

    for line in errors:
        print(line)
    print(f"Checked {len(trees)} XML files, {len(defined)} include definitions: "
          f"{len(errors)} problem(s).")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
